// Helper functions to convert sqlc types to our domain types

func sqlcOrganizationToOrganization(o any) Organization {
	var id, name, slug, createdAt, updatedAt string
	switch v := o.(type) {
	case sqlc.GetOrganizationRow:
		id, name, slug, createdAt, updatedAt = v.ID, v.Name, v.Slug, v.CreatedAt, v.UpdatedAt
	case sqlc.GetOrganizationBySlugRow:
		id, name, slug, createdAt, updatedAt = v.ID, v.Name, v.Slug, v.CreatedAt, v.UpdatedAt
	case sqlc.ListUserOrganizationsRow:
		id, name, slug, createdAt, updatedAt = v.ID, v.Name, v.Slug, v.CreatedAt, v.UpdatedAt
	}
	createdAtTime, err := time.Parse(time.RFC3339, createdAt)
	if err != nil {
		createdAtTime = time.Now()
	}
	updatedAtTime, err := time.Parse(time.RFC3339, updatedAt)
	if err != nil {
		updatedAtTime = time.Now()
	}
	return Organization{
		ID:        id,
		Name:      name,
		Slug:      slug,
		CreatedAt: createdAtTime,
		UpdatedAt: updatedAtTime,
	}
}

func sqlcMemberToMember(m sqlc.Member) Member {
	createdAt, err := time.Parse(time.RFC3339, m.CreatedAt)
	_ = err
	updatedAt, err := time.Parse(time.RFC3339, m.UpdatedAt)
	_ = err
	return Member{
		ID:             m.ID,
		UserID:         m.UserID,
		OrganizationID: m.OrganizationID,
		Role:           m.Role,
		CreatedAt:      createdAt,
		UpdatedAt:      updatedAt,
	}
}

func sqlcTeamToTeam(t sqlc.Team) Team {
	createdAt, err := time.Parse(time.RFC3339, t.CreatedAt)
	_ = err
	updatedAt, err := time.Parse(time.RFC3339, t.UpdatedAt)
	_ = err
	description := ""
	if t.Description.Valid {
		description = t.Description.String
	}
	return Team{
		ID:             t.ID,
		OrganizationID: t.OrganizationID,
		Name:           t.Name,
		Description:    description,
		CreatedAt:      createdAt,
		UpdatedAt:      updatedAt,
	}
}

func sqlcTeamMemberToTeamMember(m sqlc.TeamMember) TeamMember {
	createdAt, err := time.Parse(time.RFC3339, m.CreatedAt)
	_ = err
	updatedAt, err := time.Parse(time.RFC3339, m.UpdatedAt)
	_ = err
	return TeamMember{
		ID:        m.ID,
		TeamID:    m.TeamID,
		UserID:    m.UserID,
		Role:      m.Role,
		CreatedAt: createdAt,
		UpdatedAt: updatedAt,
	}
}
